class DemoEventsSeeder extends Seeder
{
    public function run(): void
    {
        foreach ($this->events() as $data) {
            $organization = DemoData::organization($data['eo']);

            $event = Event::updateOrCreate(
                ['slug' => $data['slug']],
                [
                    'eo_organization_id' => $organization->id,
                    'title' => $data['title'],
                    'category' => $data['category'],
                    'format' => $data['format'],
                    'date_start' => $data['date_start'],
                    'date_end' => $data['date_end'] ?? null,
                    'location' => $data['location'],
                    'description' => $data['description'],
                    'audience_profile' => $data['audience_profile'],
                    'capacity_estimate' => $data['capacity_estimate'],
                    'support_needs' => $data['support_needs'],
                    'status' => $data['status'],
                    'published_at' => $data['published_at'] ?? null,
                    'moderation_reason_internal' => $data['moderation_reason_internal'] ?? null,
                    'moderation_reason_public' => $data['moderation_reason_public'] ?? null,
                ]
            );

            $event->audienceEvidence()->delete();

            foreach ($data['evidence'] as $evidence) {
                $event->audienceEvidence()->create([
                    'evidence_type' => $evidence[0],
                    'value' => $evidence[1],
                    'unit' => $evidence[2],
                    'period' => $evidence[3],
                    'source_description' => $evidence[4],
                    'evidence_note' => $evidence[5],
                    'verification_status' => $evidence[6] ?? EvidenceVerificationStatus::Declared,
                ]);
            }

            $event->packages()->delete();

            foreach ($data['packages'] as $package) {
                $event->packages()->create($package);
            }
        }
    }

